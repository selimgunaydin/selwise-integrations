const en = (dict: Record<string, string>, tr: string) => dict[tr] ?? tr;

/** The English words of one product; everything the language feed writes. */
export function englishProduct(p: Pick<Product, 'name' | 'colorName' | 'categoryPath' | 'brand'>) {
  const name = en(MODEL_EN, p.name);
  const color = en(COLOR_EN, p.colorName);
  const path = p.categoryPath.map((c) => en(CATEGORY_EN, c));
  return {
    title: `${name} ${color}`,
    description: `${name} in ${color.toLowerCase()}. Designed by the Ardisa design team and made under responsible production principles. Part of ${path.join(' › ')} by ${p.brand}.`,
    categoryPath: path,
  };
}

/** How many catalogue names have no English word yet — the feed's own coverage check. */
export function missingEnglishNames(products: ReadonlyArray<Pick<Product, 'name' | 'colorName' | 'categoryPath'>>) {
  const missing = new Set<string>();
  for (const p of products) {
    if (!MODEL_EN[p.name]) missing.add(p.name);
    if (!COLOR_EN[p.colorName]) missing.add(p.colorName);
    for (const c of p.categoryPath) if (!CATEGORY_EN[c]) missing.add(c);
  }
  return [...missing];
}
